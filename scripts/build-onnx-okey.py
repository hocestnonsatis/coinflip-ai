"""Export the okey value net to static/model/okey-<params>.onnx + src/lib/okey-weights.ts (TS fallback) and check parity.
Run: python3 scripts/build-onnx-okey.py train-okey/best.npz [tau]"""
import sys, json, os, numpy as np, onnx, onnxruntime as ort
from onnx import helper as h, TensorProto as T, numpy_helper as nh
sys.path.insert(0, 'train-okey')
from ai import Net, NF, NH
net = Net.load(sys.argv[1] if len(sys.argv) > 1 else 'train-okey/best.npz')
tau = float(sys.argv[2]) if len(sys.argv) > 2 else 0.0
W1, b1, W2, b2 = (np.asarray(a, np.float32) for a in (net.W1.T, net.b1, net.W2.reshape(NH, 1), np.array([net.b2])))
inits = [nh.from_array(W1, 'W1'), nh.from_array(b1, 'b1'), nh.from_array(W2, 'W2'), nh.from_array(b2, 'b2')]
nodes = [h.make_node('MatMul', ['x', 'W1'], ['a']), h.make_node('Add', ['a', 'b1'], ['z']), h.make_node('Tanh', ['z'], ['hdn']),
         h.make_node('MatMul', ['hdn', 'W2'], ['o']), h.make_node('Add', ['o', 'b2'], ['zo']), h.make_node('Sigmoid', ['zo'], ['p'])]
P = net.params
name = f'okey-{P}'
g = h.make_graph(nodes, name, [h.make_tensor_value_info('x', T.FLOAT, ['N', NF])], [h.make_tensor_value_info('p', T.FLOAT, ['N', 1])], inits)
m = h.make_model(g, producer_name='tiny-models', opset_imports=[h.make_opsetid('', 17)], ir_version=8,
                 doc_string=f'Okey-{P}: TD(lambda) self-play value net for classic Turkish okey, {NF}-{NH}-1 (tanh, sigmoid). Input: hand features after a discard. Output: P(this player wins).')
assert sum(int(np.prod(i.dims)) for i in m.graph.initializer) == P
m.metadata_props.add(key='parameters', value=str(P))
onnx.checker.check_model(m); path = f'static/model/{name}.onnx'; onnx.save(m, path)
s = ort.InferenceSession(path)
X = np.random.default_rng(0).random((500, NF)).astype(np.float32)
p = s.run(None, {'x': X})[0][:, 0]; ref = net.vbatch(X.astype(np.float64))
worst = float(np.abs(p - ref).max()); assert worst < 1e-5, worst
r7 = lambda a: [float(f'{v:.7g}') for v in np.asarray(a).ravel()]
open('src/lib/okey-weights.ts', 'w').write(f'// Generated by scripts/build-onnx-okey.py — same weights as {path} (TS fallback).\n'
  f"export const MODEL_URL = '/model/{name}.onnx';\nexport const PARAMS = {P};\nexport const TAU = {tau}; // take the discard only if it beats keeping the hand by more than this\n"
  f'export const W1 = {json.dumps(r7(net.W1))}; // {NH}×{NF} row-major\nexport const B1 = {json.dumps(r7(net.b1))};\nexport const W2 = {json.dumps(r7(net.W2))};\nexport const B2 = {float(net.b2):.7g};\n')
json.dump([{'x': [float(v) for v in X[k]], 'p': float(p[k])} for k in range(30)], open('tests/okey-model.json', 'w'))
print(json.dumps({'params': P, 'onnx': path, 'onnx_bytes': os.path.getsize(path), 'max_abs_diff': worst}))
