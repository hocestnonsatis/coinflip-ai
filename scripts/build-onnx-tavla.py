"""Export a trained TD(λ) checkpoint to static/model/tavla-1.6k.onnx + src/lib/tavla-weights.ts (TS fallback), and verify parity.
Run: python3 scripts/build-onnx-tavla.py train/best.npz"""
import sys, json, numpy as np, onnx, onnxruntime as ort
from onnx import helper as h, TensorProto as T, numpy_helper as nh
sys.path.insert(0, 'train')
from net import Net
from bg import start, flip, legal, encode_batch
import random
net = Net.load(sys.argv[1] if len(sys.argv) > 1 else 'train/best.npz')
W1, b1, W2, b2 = (np.asarray(a, np.float32) for a in (net.W1, net.b1, net.W2.reshape(8, 1), np.array([net.b2])))
inits = [nh.from_array(W1, 'W1'), nh.from_array(b1, 'b1'), nh.from_array(W2, 'W2'), nh.from_array(b2, 'b2')]
nodes = [h.make_node('MatMul', ['x', 'W1'], ['a']), h.make_node('Add', ['a', 'b1'], ['z']), h.make_node('Sigmoid', ['z'], ['hdn']),
         h.make_node('MatMul', ['hdn', 'W2'], ['o']), h.make_node('Add', ['o', 'b2'], ['zo']), h.make_node('Sigmoid', ['zo'], ['p'])]
g = h.make_graph(nodes, 'Tavla-1.6K', [h.make_tensor_value_info('x', T.FLOAT, ['N', 198])], [h.make_tensor_value_info('p', T.FLOAT, ['N', 1])], inits)
m = h.make_model(g, producer_name='tiny-models', opset_imports=[h.make_opsetid('', 17)], ir_version=8,
                 doc_string='Tavla-1.6K: TD(lambda) self-play backgammon value net, 198-8-1 sigmoid. Output: P(player who just moved wins).')
n = sum(int(np.prod(i.dims)) for i in m.graph.initializer)
m.metadata_props.add(key='parameters', value=str(n))
onnx.checker.check_model(m); onnx.save(m, 'static/model/tavla-1.6k.onnx')
s = ort.InferenceSession('static/model/tavla-1.6k.onnx')
rng = random.Random(0); worst = 0; agree = 0; tot = 0
for _ in range(300):
    b = start()
    for ply in range(rng.randrange(1, 80)):
        r = rng.choice(list(legal(b, rng.randint(1, 6), rng.randint(1, 6))))
        if r[26] == 15: break
        b = flip(r)
    ks = list(legal(b, rng.randint(1, 6), rng.randint(1, 6))); X = encode_batch(ks)
    p = s.run(None, {'x': X})[0][:, 0]; ref = net.fwd(X.astype(np.float64))[0]
    worst = max(worst, float(np.abs(p - ref).max())); agree += int(np.argmax(p) == np.argmax(ref)); tot += 1
assert worst < 1e-5, worst
r6 = lambda a: [float(f'{v:.7g}') for v in np.asarray(a).ravel()]
open('src/lib/tavla-weights.ts', 'w').write('// Generated by scripts/build-onnx-tavla.py — same weights as static/model/tavla-1.6k.onnx (TS fallback).\n'
  f'export const W1 = {json.dumps(r6(W1))}; // 198×8 row-major\nexport const B1 = {json.dumps(r6(b1))};\nexport const W2 = {json.dumps(r6(W2))};\nexport const B2 = {float(b2[0]):.7g};\n')
import os
print(json.dumps({'params': n, 'onnx_bytes': os.path.getsize('static/model/tavla-1.6k.onnx'), 'max_abs_diff': worst, 'argmax_agree': f'{agree}/{tot}'}))
# Parity fixture for the TS fallback (tests/tavla.test.ts): 40 boards → onnxruntime p.
fx = []
for _ in range(40):
    b = start()
    for ply in range(rng.randrange(1, 60)):
        r = rng.choice(list(legal(b, rng.randint(1, 6), rng.randint(1, 6))))
        if r[26] == 15: break
        b = flip(r)
    fx.append({'b': list(b), 'p': float(s.run(None, {'x': encode_batch([b])})[0][0, 0])})
json.dump(fx, open('tests/tavla-model.json', 'w'))
