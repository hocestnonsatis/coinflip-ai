"""Export the trained cat: ONNX step model (static/model/kedi-<n>k.onnx), TS weights (src/lib/kedi-weights.ts) and parity
fixtures (tests/kedi-fixtures.json: a real episode's frames → PyTorch probabilities, checked against TS and ONNX).
python3 train-cat/export.py [ckpt]"""
import sys, os, json, base64, numpy as np, torch, torch.nn as nn
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from train import Kedi, KediB, load, frames_of, nparams, H_, W_
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
ck = sys.argv[1] if len(sys.argv) > 1 else f'{HERE}/ckpt/best.pt'
sd0 = torch.load(ck, weights_only=False)['model']; arch = 'belief' if sd0['head.weight'].shape[0] == 12 else 'gru'
m = KediB() if arch == 'belief' else Kedi(); m.load_state_dict(sd0); m.eval()
n = nparams(m); name = f'kedi-{round(n / 1000)}k'

class Step(nn.Module):
    """One frame: (x, prev, h, lb) → (p, h1, lb1). x/prev: (1,1,32,64) in [0,1]; lb = log-belief (1,3); same math as forward()."""
    def __init__(s, k):
        super().__init__(); s.k = k; s.cell = nn.GRUCell(k.fc.out_features, k.gru.hidden_size)
        s.cell.weight_ih.data = k.gru.weight_ih_l0.data; s.cell.weight_hh.data = k.gru.weight_hh_l0.data
        s.cell.bias_ih.data = k.gru.bias_ih_l0.data; s.cell.bias_hh.data = k.gru.bias_hh_l0.data
    def forward(s, x, prev, h, lb):
        f = s.k.features(x[:, 0], prev[:, 0]); h1 = s.cell(f, h); o = s.k.head(h1)
        if arch == 'belief':
            lt = torch.log_softmax(o[:, :9].reshape(-1, 3, 3), -1)
            nb = torch.logsumexp(lb.unsqueeze(-1) + lt, 1) + o[:, 9:]
        else:
            nb = o
        lb1 = torch.log_softmax(nb, -1)
        return torch.exp(lb1), h1, lb1
st = Step(m).eval()
hid = m.gru.hidden_size
x0 = torch.rand(1, 1, H_, W_); h0 = torch.zeros(1, hid); lb0 = torch.full((1, 3), -np.log(3.0), dtype=torch.float32)
onnx_path = f'{ROOT}/static/model/{name}.onnx'
torch.onnx.export(st, (x0, x0, h0, lb0), onnx_path, input_names=['x', 'prev', 'h', 'lb'], output_names=['p', 'h1', 'lb1'], opset_version=17, dynamo=False)
# TS weights in the state_dict order the TS code expects
order = ['c1.weight', 'c1.bias', 'c2.weight', 'c2.bias', 'c3.weight', 'c3.bias', 'fc.weight', 'fc.bias', 'gru.weight_ih_l0', 'gru.weight_hh_l0', 'gru.bias_ih_l0', 'gru.bias_hh_l0', 'head.weight', 'head.bias']
sd = m.state_dict(); flat = np.concatenate([sd[k].numpy().astype(np.float32).ravel() for k in order])
meta = {'hid': hid, 'feat': m.fc.out_features, 'arch': arch, 'shapes': [[k, list(sd[k].shape)] for k in order]}
with open(f'{ROOT}/src/lib/kedi-weights.ts', 'w') as f:
    f.write(f'// Generated by train-cat/export.py from {os.path.relpath(ck, ROOT)}: same weights as static/model/{name}.onnx (TS engine + parity check).\n')
    f.write(f"export const MODEL_URL = '/model/{name}.onnx';\nexport const NAME = 'Kedi‑{round(n / 1000)}K';\nexport const PARAMS = {n};\n")
    f.write(f"export const META = {json.dumps(meta)} as {{ hid: number; feat: number; arch: 'gru' | 'belief'; shapes: [string, number[]][] }};\n")
    f.write(f"export const B64 = '{base64.b64encode(flat.tobytes()).decode()}';\n")
# parity fixture: first frames of a real (validation) episode
eps, mm = load(f'{HERE}/data'); e = next(e for e in eps if e['seed'] % 20 == 0 and e['n'] >= 60)
fr = frames_of(e, mm)[:60]
with torch.no_grad():
    p = torch.softmax(m(torch.from_numpy(fr.astype(np.float32)[None] / 255)), -1)[0].numpy()  # (log_softmax of KediB's log-belief = itself)
import onnxruntime as ort
sess = ort.InferenceSession(onnx_path); h = np.zeros((1, hid), np.float32); lb = np.full((1, 3), -np.log(3.0), np.float32); po = []
for t in range(len(fr)):
    x = fr[t].astype(np.float32)[None, None] / 255; pv = fr[max(t - 1, 0)].astype(np.float32)[None, None] / 255
    pp, h, lb = sess.run(['p', 'h1', 'lb1'], {'x': x, 'prev': pv, 'h': h, 'lb': lb}); po.append(pp[0])
po = np.array(po); d = float(np.abs(po - p).max()); assert d < 1e-4, d
json.dump({'seed': e['seed'], 'frames': base64.b64encode(fr.tobytes()).decode(), 'p': p.round(6).tolist(), 'p_onnx': po.round(6).tolist(), 'onnx_vs_torch': d}, open(f'{ROOT}/tests/kedi-fixtures.json', 'w'))
print(json.dumps({'arch': arch, 'name': name, 'params': n, 'onnx_bytes': os.path.getsize(onnx_path), 'weights_floats': int(flat.size)}))
