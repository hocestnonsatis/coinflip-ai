"""Real numbers for the model card: final-frame accuracy on held-out rounds, the swaps × speed grid, and two honesty checks
(blank feed → ~uniform, mirrored feed → mirrored answer). Writes train-cat/eval.json and src/lib/kedi-stats.ts.
python3 train-cat/eval.py [ckpt]"""
import sys, os, json, random, numpy as np, torch, torch.nn.functional as F
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from train import Kedi, KediB, load, evaluate, batch, nparams, H_, W_
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
ck = sys.argv[1] if len(sys.argv) > 1 else f'{HERE}/ckpt/best.pt'
sd = torch.load(ck, weights_only=False)['model']
m = KediB() if sd['head.weight'].shape[0] == 12 else Kedi(); m.load_state_dict(sd); m.eval()

eps, mm = load(f'{HERE}/data'); val = [e for e in eps if e['seed'] % 20 in (10, 15)]  # test split: not trained on, not used for checkpoint selection
rv = evaluate(m, val, mm)
geps, gmm = load(f'{HERE}/data-grid'); rg = evaluate(m, geps, gmm)
SW = sorted({e['swaps'] for e in geps}); SP = sorted({round(e['speed'], 3) for e in geps})
cells = [[[0, 0] for _ in SP] for _ in SW]
for e, r in zip(geps, rg):
    c = cells[SW.index(e['swaps'])][SP.index(round(e['speed'], 3))]; c[0] += r['ok']; c[1] += 1
from kedi_dur import swap_dur  # same formula as kedi-anim.ts
speeds = [{'s': s, 'ms': round(swap_dur(s) * 1000)} for s in SP]

# honesty 1: blank / constant / noise feeds of various lengths → the final distribution should be ~uniform
rnd = random.Random(7); P = []
with torch.no_grad():
    for k in range(120):
        T = rnd.randint(30, 400); kind = k % 3
        x = np.full((1, T, H_, W_), rnd.random(), np.float32) if kind == 0 else (np.random.rand(1, T, H_, W_).astype(np.float32) if kind == 1 else np.full((1, T, H_, W_), 90 / 255, np.float32))
        P.append(F.softmax(m(torch.from_numpy(x)), -1)[0, -1].numpy())
P = np.array(P)
# honesty 2: mirrored frames must give the mirrored answer (left ↔ right), on held-out rounds
agree = 0; n = 0
with torch.no_grad():
    for k in range(0, len(val), 32):
        ids = list(range(k, min(len(val), k + 32)))
        X, Y, Wt, U, L = batch(val, mm, ids, None, train=False)
        a = F.softmax(m(X), -1); b = F.softmax(m(torch.flip(X, [3])), -1)
        for j in range(len(ids)):
            pa = int(a[j, L[j] - 1].argmax()); pb = int(b[j, L[j] - 1].argmax()); agree += int(pb == 2 - pa); n += 1
# honesty 3 (leak ablation): rounds rendered with NOTOY=1 (toy drawn only while a cup is lifted, i.e. during the hide)
notoy = None
if os.path.isdir(f'{HERE}/data-notoy'):
    neps, nmm = load(f'{HERE}/data-notoy'); rn = evaluate(m, neps, nmm); notoy = {'ok': sum(r['ok'] for r in rn), 'n': len(rn)}
acc = lambda rs: sum(r['ok'] for r in rs) / max(1, len(rs))
log = open(f'{HERE}/ckpt/log.txt').read().strip().split('\n') if os.path.exists(f'{HERE}/ckpt/log.txt') else []
meta = json.load(open(f'{HERE}/ckpt/meta.json')) if os.path.exists(f'{HERE}/ckpt/meta.json') else {}
# the training set grew while training ran: count only the rounds the final epoch actually saw (lowest seeds per worker ≈ first written)
TR = sorted((e for e in eps if e['seed'] % 20 not in (0, 10, 15)), key=lambda e: e['seed'])[:meta.get('train_rounds_last_epoch', 10**9)]
out = {
    'ckpt': os.path.relpath(ck, ROOT), 'params': nparams(m),
    'train_episodes': len(TR), 'train_frames': int(sum(e['n'] for e in TR)), 'val_episodes': len(val),
    'val_acc': acc(rv), 'val_ok': sum(r['ok'] for r in rv),
    'grid': {'swaps': SW, 'speeds': speeds, 'cells': cells, 'acc': acc(rg), 'n': len(rg)},
    'blank': {'maxP': float(P.max()), 'minP': float(P.min()), 'n': len(P)}, 'mirror': {'agree': agree, 'n': n}, 'notoy': notoy,
    'by_swaps_val': {}, **meta
}
for lo, hi in [(0, 0), (1, 5), (6, 15), (16, 40)]:
    rs = [r for r in rv if lo <= r['swaps'] <= hi]; out['by_swaps_val'][f'{lo}-{hi}'] = [sum(r['ok'] for r in rs), len(rs)]
json.dump(out, open(f'{HERE}/eval.json', 'w'), indent=1)
onnx = [f for f in os.listdir(f'{ROOT}/static/model') if f.startswith('kedi-')]
ob = os.path.getsize(f'{ROOT}/static/model/{onnx[0]}') if onnx else 0
with open(f'{ROOT}/src/lib/kedi-stats.ts', 'w') as f:
    f.write('// Generated by train-cat/eval.py — real numbers only (train-cat/eval.json). overall = final-frame accuracy on held-out random rounds\n')
    f.write('// (seed % 20 in {10, 15}: never trained on, not used to pick the checkpoint); cells = held-out pure-shuffle rounds per swaps × speed: [correct, rounds].\n')
    f.write('export const KEDI_STATS = ' + json.dumps({
        'params': out['params'], 'episodes': out['train_episodes'], 'frames': out['train_frames'], 'epochs': meta.get('epochs', 0), 'minutes': meta.get('minutes', 0), 'procs': meta.get('procs', 0), 'onnxBytes': ob,
        'overall': {'w': out['val_ok'], 'n': len(rv)}, 'blank': {'maxP': round(out['blank']['maxP'], 4), 'minP': round(out['blank']['minP'], 4), 'n': len(P)}, 'mirror': out['mirror'], 'notoy': notoy or {'ok': 0, 'n': 0},
        'swaps': SW, 'speeds': speeds, 'cells': cells}) + ';\n')
print(json.dumps({k: out[k] for k in ['val_acc', 'val_episodes', 'blank', 'mirror', 'notoy', 'by_swaps_val']}))
for i, s in enumerate(SW): print(f'{s:>3} swaps: ' + '  '.join(f'{c[0]}/{c[1]}' for c in cells[i]))
