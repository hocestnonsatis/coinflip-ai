"""Sleepy cat: the shipped model (not retrained) fed only every k-th 30 Hz camera tick (30 / 15 / 10 / 5 fps of game time).
Exact emulation from the stored 30 Hz frames: the frame at tick j is the last stored frame at or before j (dropped frames were
identical to the previous one); consecutive identical frames are dropped again, as in the browser.
Held-out grid rounds (train-cat/data-grid). Writes train-cat/eval-sleepy.json and src/lib/kedi-sleepy-stats.ts.
python3 train-cat/eval_sleepy.py [ckpt]"""
import sys, os, json, numpy as np, torch, torch.nn.functional as F
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from train import Kedi, KediB, load, frames_of
from kedi_dur import swap_dur
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
ck = sys.argv[1] if len(sys.argv) > 1 else f'{HERE}/ckpt/last.pt'
sd = torch.load(ck, weights_only=False)['model']; m = KediB() if sd['head.weight'].shape[0] == 12 else Kedi(); m.load_state_dict(sd); m.eval()
torch.set_num_threads(int(os.environ.get('THREADS', '4')))
eps, mm = load(f'{HERE}/data-grid')
FPS = [30, 15, 10, 5]
def sub(e, k):
    fr = frames_of(e, mm); t0 = e['hides'][0][0]
    ticks = [round((t - t0) * 30 / 1000) for t in e['times']]
    last = max(ticks); keep = []; i = 0; prev = None
    for j in range(0, last + 1, k):
        while i + 1 < len(ticks) and ticks[i + 1] <= j: i += 1
        if ticks[i] > j: continue
        if prev is not None and prev == i: continue  # same stored frame = identical image → dropped
        keep.append(i); prev = i
    if keep[-1] != len(ticks) - 1 and (last % k): pass  # the browser stops at the last tick ≤ end that is a multiple of k
    return fr[keep]
SW = sorted({e['swaps'] for e in eps}); SP = sorted({round(e['speed'], 3) for e in eps})
res = {f: [[[0, 0] for _ in SP] for _ in SW] for f in FPS}; nfr = {f: [] for f in FPS}
with torch.no_grad():
    for e in eps:
        y = int(e['labels'][-1])
        for f in FPS:
            x = sub(e, 30 // f).astype(np.float32) / 255; nfr[f].append(len(x))
            p = F.softmax(m(torch.from_numpy(x)[None]), -1)[0, -1].numpy()
            c = res[f][SW.index(e['swaps'])][SP.index(round(e['speed'], 3))]; c[0] += int(p.argmax() == y); c[1] += 1
out = {'fps': FPS, 'swaps': SW, 'speeds': [{'s': s, 'ms': round(swap_dur(s) * 1000)} for s in SP], 'cells': {str(f): res[f] for f in FPS},
       'frames_mean': {str(f): round(float(np.mean(nfr[f])), 1) for f in FPS}, 'n': len(eps)}
json.dump(out, open(f'{HERE}/eval-sleepy.json', 'w'), indent=1)
with open(f'{ROOT}/src/lib/kedi-sleepy-stats.ts', 'w') as fh:
    fh.write('// Generated by train-cat/eval_sleepy.py — the shipped cat (not retrained) fed every k-th camera tick. Held-out grid rounds; cells[fps][swaps][speed] = [correct, rounds].\n')
    fh.write('export const KEDI_SLEEPY = ' + json.dumps({'fps': FPS, 'swaps': SW, 'speeds': out['speeds'], 'cells': [res[f] for f in FPS]}) + ';\n')
for f in FPS:
    tot = sum(c[0] for r in res[f] for c in r), sum(c[1] for r in res[f] for c in r)
    print(f'{f:>2} fps: {tot[0]}/{tot[1]}  frames/round {out["frames_mean"][str(f)]}')
    for i, s in enumerate(SW): print(f'   {s:>3} swaps: ' + '  '.join(f'{c[0]:>2}/{c[1]}' for c in res[f][i]))
