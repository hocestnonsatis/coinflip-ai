"""Cheat eval: the shipped cat (never trained on stickers) against toy pictures stuck on cups (cdp-kedi-datagen.mjs STICK=…).
Writes train-cat/eval-stick.json and src/lib/kedi-stick-stats.ts. Real numbers only.
python3 train-cat/eval_stick.py [ckpt]"""
import sys, os, json, glob, subprocess, torch
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from train import Kedi, KediB, load, evaluate
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
ck = sys.argv[1] if len(sys.argv) > 1 else f'{HERE}/ckpt/last.pt'
sd = torch.load(ck, weights_only=False)['model']; m = KediB() if sd['head.weight'].shape[0] == 12 else Kedi(); m.load_state_dict(sd); m.eval()
GRID, S0 = '0,1,3,8,20:0.3,0.7,0.95', 8000000
ORDER = ['wrong-before', 'wrong-after', 'empty-before', 'all-before', 'all-after', 'right-before', 'right-after']
node = os.path.expanduser('~/.local/node22/bin/node')
out = {}
for name in ORDER:
    d = f'{HERE}/data-stick/{name}'
    if not glob.glob(f'{d}/w*.jsonl'): continue
    eps, mm = load(d); rs = evaluate(m, eps, mm)
    fin = json.loads(subprocess.check_output([node, '--experimental-strip-types', f'{HERE}/final_at.ts', str(S0), str(max(e['seed'] for e in eps) - S0 + 1), GRID], cwd=ROOT, stderr=subprocess.DEVNULL))
    ok = fooled = 0; ps = []; by = {}
    for e, r in zip(eps, rs):
        at = fin[str(e['seed'])]; on = e['stick']['on']; stickSlots = [s for s in range(3) if on[at[s]]]
        ok += r['ok']; ps.append(r['p'])
        if not r['ok'] and r['choice'] in stickSlots: fooled += 1
        k = 'swaps0' if e['swaps'] == 0 else 'swaps1+'; by.setdefault(k, [0, 0]); by[k][0] += r['ok']; by[k][1] += 1
    out[name] = {'ok': ok, 'n': len(rs), 'fooled': fooled, 'meanP': round(sum(ps) / len(ps), 4), 'by': by}
    print(name, out[name], flush=True)
json.dump(out, open(f'{HERE}/eval-stick.json', 'w'), indent=1)
with open(f'{ROOT}/src/lib/kedi-stick-stats.ts', 'w') as f:
    f.write('// Generated by train-cat/eval_stick.py — the shipped cat (never trained on stickers) vs toy pictures on cups. Real numbers only.\n')
    f.write('// ok/n = right answers; fooled = wrong answers that pointed at a cup with a sticker; meanP = mean confidence of the answer.\n')
    f.write('export const KEDI_STICK = ' + json.dumps([{'id': k, **{x: v[x] for x in ('ok', 'n', 'fooled', 'meanP')}} for k, v in out.items()]) + ';\n')
